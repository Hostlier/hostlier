package nginx

import (
	"encoding/json"
	"os"
	"os/exec"
	"path/filepath"
	"testing"
)

// TestLiveVMTrafficPolicies runs generated policies on an isolated listener beside the VM's installed edge.
func TestLiveVMTrafficPolicies(t *testing.T) {
	// This fixture never guesses a production host, certificate, port or deployment identity.
	if os.Getenv("HOSTLIER_TRAFFIC_POLICY_VM") != "1" {
		t.Skip("explicit disposable traffic-policy VM required")
	}
	host, _ := os.Hostname()
	marker, err := os.ReadFile("/root/hostlier-cold-cli-e2e/fixture")
	// Root ownership and the exact test VM marker fence certificate and listener use.
	if err != nil || host != "lima-hostlier-cli-deploy" || string(marker) != "hostlier-cold-cli-e2e-v1\n" || os.Geteuid() != 0 {
		t.Fatal("wrong traffic-policy VM fixture")
	}
	root := "/root/hostlier-traffic-e2e/nginx"
	var fixture struct {
		Options Options
		Routes  []Route
	}
	data, err := os.ReadFile(filepath.Join(root, "fixture.json"))
	// Route metadata contains no application credentials or certificate contents.
	if err != nil {
		t.Fatal(err)
	}
	// The fixture is generated from the real Hostlier deployments' reviewed endpoint records.
	if err := json.Unmarshal(data, &fixture); err != nil {
		t.Fatal(err)
	}
	configuration, err := Render(fixture.Options, "", "", fixture.Routes)
	// Unsupported policies must fail before starting any independent Nginx listener.
	if err != nil {
		t.Fatal(err)
	}
	path := filepath.Join(root, "nginx.conf")
	// Persist generated bytes only in the root-owned disposable test directory.
	if err := os.WriteFile(path, configuration, 0600); err != nil {
		t.Fatal(err)
	}
	runEndpointFixture(t, "nginx", "-t", "-c", path)
	runEndpointFixture(t, "nginx", "-c", path)
	// Always release the isolated test listener without restarting Caddy or the controller.
	t.Cleanup(func() { _ = exec.Command("nginx", "-s", "quit", "-c", path).Run() })
	runEndpointFixture(t, "/tmp/hostlier-traffic-probe.test", "-test.v", "-test.run", "^(TestHTTP|TestSSE|TestWebSocket|TestStreamableHTTP|TestDuplex|TestNativeGRPC|TestPolicyHTTPDenials|TestPolicySDKWebhookRoute|TestPolicyEngine.*)$", "-test.timeout", "45s")
}
