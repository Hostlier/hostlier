package packageexec

import (
	"os"
	"path/filepath"
	"strings"
	"time"
)

// UploadGrace preserves interrupted transfers and pending approvals for a day of inactivity.
const UploadGrace = 24 * time.Hour

// CleanupResult reports reclaimed inert upload bytes, never installed executables.
type CleanupResult struct {
	Files int
	Bytes int64
}

// Sweep expires abandoned uploads without requiring another client to upload first.
// Callers serialize this operation with upload reads and writes.
func (s Uploads) Sweep(now time.Time) (CleanupResult, error) {
	var result CleanupResult
	_, err := os.Lstat(s.Root)
	// An unused upload store needs no directory or cleanup work.
	if os.IsNotExist(err) {
		return result, nil
	}
	// Validate ancestry before inspecting any potential deletion target.
	if err != nil {
		return result, err
	}
	// Upload cleanup uses the same private, nonredirected storage boundary as writes.
	if err = prepareDirectory(s.Root); err != nil {
		return result, err
	}
	entries, err := os.ReadDir(s.Root)
	// An unreadable inventory cannot authorize reclamation.
	if err != nil {
		return result, err
	}
	// Only recognized actor/content identities can become deletion candidates.
	for _, entry := range entries {
		// Stop on filesystem failure so the remaining entries can be retried later.
		if err = s.sweepUpload(entry, now, &result); err != nil {
			return result, err
		}
	}
	return result, nil
}

// sweepUpload preserves recent uploads, unknown files and filesystem links.
func (s Uploads) sweepUpload(entry os.DirEntry, now time.Time, result *CleanupResult) error {
	// Both name components are hashes generated by the upload store.
	if !knownUpload(entry.Name()) {
		return nil
	}
	info, err := entry.Info()
	// Keep unreadable entries retryable instead of dropping their accounting.
	if err != nil {
		return err
	}
	// No executable, link or recently used upload is disposable staging.
	if !info.Mode().IsRegular() || info.Mode().Perm() != 0600 || now.Sub(info.ModTime()) < UploadGrace {
		return nil
	}
	// Failed removal leaves the upload available to the next scheduled sweep.
	if err = os.Remove(filepath.Join(s.Root, entry.Name())); err != nil {
		return err
	}
	result.Files++
	result.Bytes += info.Size()
	return nil
}

// knownUpload recognizes only filenames generated from an actor and content digest.
func knownUpload(name string) bool {
	owner, digest, ok := strings.Cut(name, "-")
	return ok && ValidDigest(owner) && ValidDigest(digest)
}
