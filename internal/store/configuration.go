package store

import (
	"crypto/tls"
	"encoding/json"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// collectServerConfiguration captures installed edge settings and protected TLS assets for explicit recovery.
func collectServerConfiguration(files map[string][]byte, root string) error {
	// Development stores need not have system installation assets.
	if _, err := os.Stat(root); errors.Is(err, os.ErrNotExist) {
		return nil
	}
	// Collect only safe regular controller files under the exclusive lock.
	err := filepath.WalkDir(root, func(path string, entry os.DirEntry, walkErr error) error {
		// Abort instead of silently omitting protected configuration.
		if walkErr != nil {
			return walkErr
		}
		// Directory names are recreated only after archive validation.
		if entry.IsDir() {
			return nil
		}
		// Runtime PID files describe the stopped source process, never recoverable settings.
		if filepath.ToSlash(strings.TrimPrefix(path, root+string(os.PathSeparator))) == "nginx/nginx.pid" {
			return nil
		}
		return collectConfigurationFile(files, root, path)
	})
	// No partial configuration snapshot is considered a successful backup.
	if err != nil {
		return err
	}
	return verifyTLSAssets(files)
}

// verifyTLSAssets detects certificate rotation races instead of exporting mismatched certificate/key bytes.
func verifyTLSAssets(files map[string][]byte) error {
	// Only complete certificate pairs are examined; other configuration remains opaque.
	for name, certificate := range files {
		// Certbot stores a full chain beside each active private key.
		if !strings.HasSuffix(name, "/fullchain.pem") {
			continue
		}
		keyName := strings.TrimSuffix(name, "fullchain.pem") + "privkey.pem"
		// An incomplete pair cannot support deterministic TLS recovery.
		if _, err := tls.X509KeyPair(certificate, files[keyName]); err != nil {
			return fmt.Errorf("invalid recovery TLS certificate pair: %s", name)
		}
	}
	return nil
}

// collectConfigurationFile materializes one confined regular configuration or certificate file.
func collectConfigurationFile(files map[string][]byte, root, path string) error {
	resolved, err := filepath.EvalSymlinks(path)
	// Certbot live links may resolve only within the protected configuration root.
	if err != nil {
		return err
	}
	// Validate the precondition before accepting protected state.
	if resolved != root && !strings.HasPrefix(resolved, root+string(os.PathSeparator)) {
		return errors.New("configuration link escapes protected root")
	}
	// Propagate failures before publishing recovery state.
	if err = regularOrMissing(resolved); err != nil {
		return err
	}
	info, err := os.Stat(resolved)
	// Bound package-independent configuration and certificate entries.
	if err != nil {
		return err
	}
	// Validate the precondition before accepting protected state.
	if info.Size() > 16<<20 {
		return errors.New("configuration file exceeds recovery limit")
	}
	name, err := filepath.Rel(root, path)
	// Preserve the installed relative layout under an explicit staging prefix.
	if err != nil {
		return err
	}
	// Preserve Certbot link semantics separately while keeping the tar entries regular.
	if path != resolved {
		// Abort collection if the confined link cannot be recorded.
		if err = recordConfigurationLink(files, root, path, resolved); err != nil {
			return err
		}
	}
	data, err := os.ReadFile(resolved)
	files["recovery-config/etc/hostlier/"+filepath.ToSlash(name)] = data
	return err
}

// recordConfigurationLink retains confined relative certificate links for renewal after restoration.
func recordConfigurationLink(files map[string][]byte, root, path, resolved string) error {
	links := map[string]string{}
	// Existing link metadata is generated by this collector rather than provider input.
	if raw := files["recovery-config/links.json"]; len(raw) > 0 {
		// Refuse malformed previously collected link metadata.
		if err := json.Unmarshal(raw, &links); err != nil {
			return err
		}
	}
	name, err := filepath.Rel(root, path)
	// The caller has already confined both the link and its resolved regular target.
	if err != nil {
		return err
	}
	target, err := filepath.Rel(filepath.Dir(path), resolved)
	// Relative targets remain valid when the configuration root moves between machines.
	if err != nil {
		return err
	}
	links[filepath.ToSlash(name)] = filepath.ToSlash(target)
	files["recovery-config/links.json"], err = json.Marshal(links)
	return err
}

// restoreConfigurationLinks reconstructs only internal certificate links after regular files are verified.
func restoreConfigurationLinks(dir string, files map[string][]byte) error {
	raw := files["recovery-config/links.json"]
	// Bundles without installed edge certificates require no link reconstruction.
	if len(raw) == 0 {
		return nil
	}
	var links map[string]string
	// A corrupt link manifest cannot authorize modifying the staged filesystem.
	if err := json.Unmarshal(raw, &links); err != nil {
		return err
	}
	root := filepath.Join(dir, "recovery-config", "etc", "hostlier")
	// Every generated link must remain entirely inside the protected configuration subtree.
	for name, target := range links {
		// Fail before publishing any unsafe restored certificate link.
		if err := restoreConfigurationLink(root, name, target); err != nil {
			return err
		}
	}
	return nil
}

// restoreConfigurationLink validates both endpoints before replacing a staged materialized file.
func restoreConfigurationLink(root, name, target string) error {
	path := filepath.Join(root, filepath.FromSlash(name))
	resolved := filepath.Clean(filepath.Join(filepath.Dir(path), filepath.FromSlash(target)))
	// Absolute links or traversal outside the configuration subtree are never restored.
	if filepath.IsAbs(name) || filepath.IsAbs(target) || !strings.HasPrefix(path, root+string(os.PathSeparator)) || !strings.HasPrefix(resolved, root+string(os.PathSeparator)) {
		return errors.New("unsafe recovery configuration link")
	}
	// The destination must be an already verified regular archive member.
	if err := regularOrMissing(path); err != nil {
		return err
	}
	// The resolved target must also be a present regular archive member.
	info, err := os.Lstat(resolved)
	// Propagate failures before publishing recovery state.
	if err != nil {
		return err
	}
	// Validate the precondition before accepting protected state.
	if !info.Mode().IsRegular() {
		return errors.New("configuration link target is not regular")
	}
	// Propagate failures before publishing recovery state.
	if err = os.Remove(path); err != nil {
		return err
	}
	return os.Symlink(filepath.FromSlash(target), path)
}

// collectCaddyState captures Caddy's ACME accounts and certificate cache as protected regular files.
func collectCaddyState(files map[string][]byte, root string) error {
	info, err := os.Lstat(root)
	// A development controller may have no installed Caddy state.
	if errors.Is(err, os.ErrNotExist) {
		return nil
	}
	// The state root itself must not redirect into unrelated system data.
	if err != nil {
		return err
	}
	// Require protected ordinary files before staging private Caddy state.
	if !info.IsDir() || info.Mode()&os.ModeSymlink != 0 {
		return errors.New("unsafe Caddy state root")
	}
	// Inspect each state entry without following unsupported links.
	return filepath.WalkDir(root, func(path string, entry os.DirEntry, walkErr error) error {
		// Any unreadable entry invalidates the entire snapshot.
		if walkErr != nil {
			return walkErr
		}
		// Caddy state directories are recreated with protected permissions on restoration.
		if entry.IsDir() {
			return nil
		}
		return collectCaddyFile(files, root, path)
	})
}

// collectCaddyFile rejects links and special files before staging one bounded private state file.
func collectCaddyFile(files map[string][]byte, root, path string) error {
	// Caddy state has no supported symlink contract, unlike Certbot's live directory.
	if err := regularOrMissing(path); err != nil {
		return err
	}
	info, err := os.Stat(path)
	// Reject missing, oversized or unreadable state before consuming file bytes.
	if err != nil {
		return err
	}
	// Require protected ordinary files before staging private Caddy state.
	if info.Size() > 16<<20 {
		return errors.New("Caddy state file exceeds recovery limit")
	}
	name, err := filepath.Rel(root, path)
	// Walking the explicit root guarantees the staged layout stays confined.
	if err != nil {
		return err
	}
	data, err := os.ReadFile(path)
	files["recovery-config/var/lib/caddy/"+filepath.ToSlash(name)] = data
	return err
}
