// eventTestFrame decodes the explicit wire fields needed to verify resumable SSE progress.
type eventTestFrame struct{ kind, id, data string }

// eventTestRuntime emits early sanitized progress before waiting for explicit operation completion.
type eventTestRuntime struct {
	recordingRuntime
	started chan struct{}
	release chan struct{}
}

// Deploy reports a real runtime transition while keeping the controller's job alive until released.
func (r *eventTestRuntime) Deploy(ctx context.Context, p model.Project, dc model.DeployContext) (model.Deployment, error) {
	dc.OnEvent(model.Event{Step: "health", Message: "private-runtime-secret"})
	close(r.started)
	// Stream disconnects and client revocation must not cancel the independent operation context.
	select {
	// The test permits ordinary deployment completion only after exercising subscriptions.
	case <-r.release:
		return model.Deployment{RuntimeID: "ready", Status: "running"}, nil
	// Controller shutdown still cancels the background job normally.
	case <-ctx.Done():
		return model.Deployment{}, ctx.Err()
	}
}

// eventTestController seeds a durable operation and credential before exposing a real HTTP handler.
func eventTestController(t *testing.T) (*Controller, *httptest.Server, string) {
	t.Helper()
	c := newTestController(t, t.TempDir(), &recordingRuntime{}, time.Now)
	c.mu.Lock()
	c.state.Clients["stream-client"] = &Client{ID: "stream-client", Verifier: verifier("stream-token")}
	c.state.Operations["stream-op"] = &Operation{ID: "stream-op", Kind: "deploy", Name: "sample", Status: "running", Spec: project()}
	c.log("retained progress", "stream-op", "info")
	c.mu.Unlock()
	server := httptest.NewServer(c.Handler())
	t.Cleanup(server.Close)
	// Stop subscriptions before the fixture listener waits for active request handlers.
	t.Cleanup(func() { closeController(t, c) })
	return c, server, "stream-token"
}

// openEventTestStream sends an authenticated HTTP subscription with an optional durable replay cursor.
func openEventTestStream(t *testing.T, server *httptest.Server, token, cursor string) *http.Response {
	t.Helper()
	request, err := http.NewRequest("GET", server.URL+"/v1/operations/stream-op/events", nil)
	// Require the fixture request to be valid before adding authentication headers.
	if err != nil {
		t.Fatal(err)
	}
	request.Header.Set("Authorization", "Bearer "+token)
	request.Header.Set("Last-Event-ID", cursor)
	client := &http.Client{Timeout: 3 * time.Second}
	response, err := client.Do(request)
	// A live response must arrive before a still-running background operation completes.
	if err != nil {
		t.Fatal(err)
	}
	return response
}

// readEventTestFrame consumes one complete SSE frame while ignoring transport heartbeat comments.
func readEventTestFrame(t *testing.T, reader *bufio.Scanner) eventTestFrame {
	t.Helper()
	frame := eventTestFrame{}
	// Parse the server's simple one-line JSON event format.
	for reader.Scan() {
		line := reader.Text()
		// A blank line commits one complete non-comment event.
		if line == "" && frame.kind != "" {
			return frame
		}
		key, value, _ := strings.Cut(line, ": ")
		// Accept only the three SSE fields generated by this endpoint.
		switch key {
		// Cursor identity belongs exclusively to durable public log entries.
		case "id":
			frame.id = value
		// Event names distinguish log, operation and reset payloads.
		case "event":
			frame.kind = value
		// JSON data remains intact for assertions about status and redaction.
		case "data":
			frame.data = value
		}
	}
	t.Fatalf("missing SSE frame: %v", reader.Err())
	return frame
}

// requireEventTestStatus checks a safe operation status frame with no replay identifier.
func requireEventTestStatus(t *testing.T, frame eventTestFrame, status string) {
	t.Helper()
	var operation Operation
	err := json.Unmarshal([]byte(frame.data), &operation)
	// Status frames must never consume the log replay cursor.
	if err != nil || frame.kind != "operation" || frame.id != "" || operation.Status != status {
		t.Fatalf("unexpected operation frame: %+v %v", frame, err)
	}
}

// TestOperationEventAuthenticationAndCursorValidation rejects unsafe requests before SSE headers.
func TestOperationEventAuthenticationAndCursorValidation(t *testing.T) {
	c, server, token := eventTestController(t)
	tests := []struct {
		name, token, cursor string
		status              int
	}{
		{"authentication", "", "", 401},
		{"malformed", token, "junk", 400},
		{"cross-operation", token, "other:1", 400},
		{"noncanonical", token, "stream-op:01", 400},
		{"future", token, fmt.Sprintf("stream-op:%d", c.state.EventSequence+1), 400},
	}
	// Every invalid cursor and missing credential stays on the ordinary JSON error surface.
	for _, test := range tests {
		// Isolate each authentication or replay validation failure.
		t.Run(test.name, func(t *testing.T) {
			response := openEventTestStream(t, server, test.token, test.cursor)
			defer response.Body.Close()
			body, _ := io.ReadAll(response.Body)
			// Reject before emitting any event-stream content or sensitive credential material.
			if response.StatusCode != test.status || response.Header.Get("Content-Type") != "application/json" || strings.Contains(string(body), token) {
				t.Fatalf("unexpected rejection: %d %s", response.StatusCode, body)
			}
		})
	}
}

// TestOperationEventEarlyProgressDisconnectAndRevocation keeps runtime work independent of subscribers.
func TestOperationEventEarlyProgressDisconnectAndRevocation(t *testing.T) {
	c, server, token := eventTestController(t)
	runtime := &eventTestRuntime{started: make(chan struct{}), release: make(chan struct{})}
	c.opts.Runtime = runtime
	c.mu.Lock()
	c.state.Operations["stream-op"].Status = "queued"
	c.enqueue("stream-op")
	c.mu.Unlock()
	<-runtime.started
	response := openEventTestStream(t, server, token, "")
	reader := bufio.NewScanner(response.Body)
	cursor := readThroughEarlyProgress(t, reader)
	response.Body.Close()
	// Reconnect receives current running status without replaying acknowledged progress.
	resumed := openEventTestStream(t, server, token, cursor)
	resumedReader := bufio.NewScanner(resumed.Body)
	requireEventTestStatus(t, readEventTestFrame(t, resumedReader), "running")
	requireEventAPIResponsive(t, server, token)
	c.mu.Lock()
	c.state.Clients["stream-client"].Revoked = true
	c.mu.Unlock()
	_, err := io.ReadAll(resumed.Body)
	resumed.Body.Close()
	// Revocation must close the subscription before its three-second fixture timeout.
	if err != nil {
		t.Fatal("revoked stream did not close promptly", err)
	}
	c.mu.Lock()
	status := c.state.Operations["stream-op"].Status
	c.state.Clients["stream-client"].Revoked = false
	c.mu.Unlock()
	// Neither a reader disconnect nor revocation may cancel the live job.
	if status != "running" {
		t.Fatalf("subscriber changed operation lifetime: %s", status)
	}
	close(runtime.release)
	terminal := openEventTestStream(t, server, token, cursor)
	defer terminal.Body.Close()
	body, err := io.ReadAll(terminal.Body)
	// The completed job must stream its final log followed by the terminal result and EOF.
	if err != nil || !strings.Contains(string(body), `"status":"succeeded"`) {
		t.Fatalf("missing terminal outcome: %s %v", body, err)
	}
}

// readThroughEarlyProgress verifies a sanitized runtime event arrives before the job can finish.
func readThroughEarlyProgress(t *testing.T, reader *bufio.Scanner) string {
	t.Helper()
	// Initial history may contain queued and running transitions before the runtime event.
	for range 8 {
		frame := readEventTestFrame(t, reader)
		// Public events must exclude arbitrary runtime message text and credentials.
		if strings.Contains(frame.data, "private-runtime-secret") {
			t.Fatal("runtime secret exposed")
		}
		// Capture the durable cursor only after observing real early runtime progress.
		if frame.kind == "log" && strings.Contains(frame.data, "Runtime step: health") {
			return frame.id
		}
	}
	t.Fatal("missing early runtime progress")
	return ""
}

// requireEventAPIResponsive verifies a connected subscriber does not hold the controller mutex during writes.
func requireEventAPIResponsive(t *testing.T, server *httptest.Server, token string) {
	t.Helper()
	request, _ := http.NewRequest("GET", server.URL+"/v1/operations/stream-op", nil)
	request.Header.Set("Authorization", "Bearer "+token)
	response, err := (&http.Client{Timeout: time.Second}).Do(request)
	// A regular authenticated read must finish independently of the open progress response.
	if err != nil {
		t.Fatal("stream blocked ordinary API", err)
	}
	defer response.Body.Close()
	// The same live job remains available through the existing JSON endpoint.
	if response.StatusCode != 200 {
		t.Fatal(response.StatusCode)
	}
}

// TestOperationEventReplaySurvivesControllerRestart keeps emitted cursors stable across durable recovery.
func TestOperationEventReplaySurvivesControllerRestart(t *testing.T) {
	dir := t.TempDir()
	c := newTestController(t, dir, &recordingRuntime{}, time.Now)
	// Close the latest controller instance after the explicit restart below.
	defer func() { closeController(t, c) }()
	c.mu.Lock()
	c.state.Clients["stream-client"] = &Client{ID: "stream-client", Verifier: verifier("stream-token")}
	c.state.Operations["stream-op"] = &Operation{ID: "stream-op", Status: "succeeded"}
	c.log("first", "stream-op", "info")
	first := c.state.EventSequence
	c.log("second", "stream-op", "info")
	second := c.state.EventSequence
	c.mu.Unlock()
	server := httptest.NewServer(c.Handler())
	response := openEventTestStream(t, server, "stream-token", fmt.Sprintf("stream-op:%d", first))
	reader := bufio.NewScanner(response.Body)
	frame := readEventTestFrame(t, reader)
	// Only unacknowledged logs are emitted with their original global sequence.
	if frame.id != fmt.Sprintf("stream-op:%d", second) {
		t.Fatalf("unexpected replay: %+v", frame)
	}
	requireEventTestStatus(t, readEventTestFrame(t, reader), "succeeded")
	response.Body.Close()
	server.Close()
	// Simulate process loss without a graceful shutdown save after the cursor was emitted.
	c.cancel()
	// Releasing the exclusive durable store lock allows a new process instance to recover it.
	if err := c.store.Close(); err != nil {
		t.Fatal(err)
	}
	c = newTestController(t, dir, &recordingRuntime{}, time.Now)
	restarted := httptest.NewServer(c.Handler())
	defer restarted.Close()
	replay := openEventTestStream(t, restarted, "stream-token", fmt.Sprintf("stream-op:%d", first))
	defer replay.Body.Close()
	replayReader := bufio.NewScanner(replay.Body)
	replayed := readEventTestFrame(t, replayReader)
	// Durable snapshotting must preserve the exact frame cursor and sanitized log payload.
	if replayed.id != frame.id || replayed.data != frame.data {
		t.Fatalf("unstable durable replay: %+v %+v", frame, replayed)
	}
	requireEventTestStatus(t, readEventTestFrame(t, replayReader), "succeeded")
}

// TestOperationEventExpiredHistoryResetsBeforeReplay never implies complete history after retention loss.
func TestOperationEventExpiredHistoryResetsBeforeReplay(t *testing.T) {
	c, server, token := eventTestController(t)
	c.mu.Lock()
	old := c.state.EventSequence
	// Overflow the retained global event window with related and unrelated public progress.
	for range 1002 {
		c.log("retained", "stream-op", "info")
	}
	c.state.Operations["stream-op"].Status = "succeeded"
	c.mu.Unlock()
	response := openEventTestStream(t, server, token, fmt.Sprintf("stream-op:%d", old))
	defer response.Body.Close()
	reader := bufio.NewScanner(response.Body)
	reset := readEventTestFrame(t, reader)
	// A reset must precede replay and leave the client cursor unchanged.
	if reset.kind != "reset" || reset.id != "" || reset.data != `{"reason":"history_expired"}` {
		t.Fatalf("missing retention reset: %+v", reset)
	}
	first := readEventTestFrame(t, reader)
	// The retained suffix remains available after the explicit incompleteness marker.
	if first.kind != "log" || first.id == "" {
		t.Fatalf("missing retained replay: %+v", first)
	}
}

// TestMigrateEventSequencesPreservesLegacyOrder initializes older states without timestamp sorting.
func TestMigrateEventSequencesPreservesLegacyOrder(t *testing.T) {
	c := &Controller{state: State{Events: []LogEntry{{Message: "later timestamp first", Timestamp: "z"}, {Message: "earlier timestamp second", Timestamp: "a"}}}}
	c.migrateEventSequences()
	// Retained append order determines replay, even when wall-clock timestamps moved backwards.
	if c.state.Events[0].Sequence != 1 || c.state.Events[1].Sequence != 2 || c.state.EventSequence != 2 || c.state.Events[0].Timestamp != "z" {
		t.Fatalf("legacy order changed: %+v", c.state)
	}
	c.state.EventSequence = 100
	c.migrateEventSequences()
	// Reopening already migrated state cannot reuse expired global cursor identifiers.
	if c.state.EventSequence != 100 || c.state.Events[1].Sequence != 2 {
		t.Fatal("migration rewrote stable cursors")
	}
}

// TestOperationEventPersistenceFailureDoesNotExposeCursor fails closed when a new replay snapshot cannot be saved.
func TestOperationEventPersistenceFailureDoesNotExposeCursor(t *testing.T) {
	c, server, token := eventTestController(t)
	// A closed SQLite handle reliably rejects commits before any event cursor is exposed.
	if err := c.store.Close(); err != nil {
		t.Fatal(err)
	}
	// Restore the handle before the fixture's ordinary controller shutdown.
	defer func() {
		reopened, err := store.Open(c.opts.StateDir, &State{})
		// A failed fixture reopen must not silently skip cleanup validation.
		if err != nil {
			t.Fatal(err)
		}
		c.store = reopened
	}()
	response := openEventTestStream(t, server, token, "")
	defer response.Body.Close()
	body, _ := io.ReadAll(response.Body)
	// No event-stream headers or cursor bytes may escape after failed durable persistence.
	if response.StatusCode != 400 || response.Header.Get("Content-Type") != "application/json" || !strings.Contains(string(body), "STATE_WRITE_FAILED") || strings.Contains(string(body), "id:") {
		t.Fatalf("failed snapshot exposed cursor: %d %s", response.StatusCode, body)
	}
}

// TestOperationEventCapacityBoundsLiveSubscribers rejects excess streams while ordinary API calls remain usable.
func TestOperationEventCapacityBoundsLiveSubscribers(t *testing.T) {
	_, server, token := eventTestController(t)
	responses := []*http.Response{}
	// Close all accepted streams even if an assertion fails before the capacity check.
	defer func() {
		// Release every response body so no subscription survives fixture cleanup.
		for _, response := range responses {
			response.Body.Close()
		}
	}()
	// Fill the bounded live subscription budget using real HTTP connections.
	for range eventStreamCapacity {
		responses = append(responses, openEventTestStream(t, server, token, ""))
	}
	excess := openEventTestStream(t, server, token, "")
	defer excess.Body.Close()
	// Exhausting progress subscriptions must produce a safe retryable HTTP response.
	if excess.StatusCode != 429 {
		t.Fatal("unbounded subscription capacity", excess.StatusCode)
	}
	requireEventAPIResponsive(t, server, token)
}
