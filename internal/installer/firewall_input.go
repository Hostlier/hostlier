// nftInputFiltering examines host ingress hooks and their jump targets. Its
// optional trust flag requires a recorded pinned cluster AND verified IPv4/IPv6
// iptables INPUT views; nft JSON hides compatibility-rule comments and ports. NAT-only
// tables (including Lima DNS), and Docker forward rules, are preserved untouched.
func nftInputFiltering(raw []byte, ownedCluster ...bool) (bool, error) {
	trusted := len(ownedCluster) > 0 && ownedCluster[0]
	// An empty ruleset has no observed ingress filtering.
	if len(strings.TrimSpace(string(raw))) == 0 {
		return false, nil
	}
	graph, err := parseNFTGraph(raw, trusted, len(ownedCluster) > 1 && ownedCluster[1])
	// Malformed firewall data requires review rather than permissive adoption.
	if err != nil {
		return true, err
	}
	// Inspect every host ingress entry point and all reachable jumps.
	for _, key := range graph.starts {
		// Stop when any ingress path blocks traffic or cannot be classified safely.
		if blocked, err := graph.blocks(key); blocked || err != nil {
			return blocked, err
		}
	}
	return false, nil
}

// iptablesInputFiltering rejects host INPUT restrictions outside the narrow owned cluster rules.
func iptablesInputFiltering(text string, ownedCluster bool) bool {
	// Inspect textual rules independently of opaque nft compatibility expressions.
	for _, line := range strings.Split(text, "\n") {
		// A non-accept INPUT policy is an active host ingress restriction.
		if strings.HasPrefix(line, "-P INPUT ") && !strings.HasSuffix(line, " ACCEPT") {
			return true
		}
		// Every appended INPUT rule must prove narrow recorded cluster ownership.
		if strings.HasPrefix(line, "-A INPUT ") {
			// Trust only reviewed generated rules when the cluster itself is owned.
			if ownedCluster && ownedK3sInputRule(line) {
				continue
			}
			return true
		}
	}
	return false
}

// These are the exact management rules generated by k3sAssets and the pinned
// kube-router's policy-mark accept rule. A similar comment alone is not proof
// of ownership, and no arbitrary INPUT drop or unrelated jump is exempted.
func ownedK3sInputRule(line string) bool {
	const marked = `-A INPUT -m comment --comment "KUBE-ROUTER rule to explicitly ACCEPT traffic that comply to network policies" -m mark --mark 0x20000/0x20000 -j ACCEPT`
	// Accept only the exact pinned kube-router policy-mark rule.
	if line == marked {
		return true
	}
	// Recognize generated KUBE jumps only after checking their complete textual form.
	if regexp.MustCompile(` -j KUBE-[A-Z0-9-]+$`).MatchString(line) {
		return true
	}
	const local = `-A INPUT -p tcp -m multiport --dports 6443,10250 -m addrtype --src-type LOCAL -m comment --comment hostlier-k3s-local -j ACCEPT`
	const pods = `-A INPUT -s 10.42.0.0/16 -p tcp -m multiport --dports 6443,10250 -m comment --comment hostlier-k3s-pods -j ACCEPT`
	const private = `-A INPUT -p tcp -m multiport --dports 6443,10250 -m comment --comment hostlier-k3s-private -j REJECT`
	return line == local || line == pods || line == private || line == private+" --reject-with icmp-port-unreachable" || line == private+" --reject-with icmp6-port-unreachable"
}

// firewallView captures policy and INPUT rules from one IP-family tool.
func firewallView(ctx context.Context, tool string) (string, bool) {
	probe, cancel := context.WithTimeout(ctx, 20*time.Second)
	defer cancel()
	var warnings bytes.Buffer
	cmd := exec.CommandContext(probe, tool, "-S")
	cmd.Stderr = &warnings
	output, err := cmd.Output()
	return strings.TrimSpace(string(output)), err == nil && strings.TrimSpace(warnings.String()) == ""
}

// Require complete IPv4 and IPv6 INPUT mirrors before trusting opaque xt rules.
// An omitted/unrepresentable native rule must never broaden the exception.
func nftInputViewsMatch(raw []byte, ipv4, ipv6 string) bool {
	var document struct {
		NFTables []struct {
			Rule *struct{ Family, Table, Chain string } `json:"rule"`
		} `json:"nftables"`
	}
	// Invalid nft data cannot demonstrate agreement with textual views.
	if json.Unmarshal(raw, &document) != nil {
		return false
	}
	counts := map[string]int{}
	// Count only host INPUT compatibility rules in the filter table.
	for _, entry := range document.NFTables {
		// Record each family separately so IPv4 cannot stand in for IPv6 verification.
		if entry.Rule != nil && entry.Rule.Table == "filter" && entry.Rule.Chain == "INPUT" {
			counts[entry.Rule.Family]++
		}
	}
	// Compare nft rule counts with independently captured textual INPUT rules.
	count := func(text string) int {
		total := 0
		// Count every appended INPUT rule in the textual view.
		for _, line := range strings.Split(text, "\n") {
			// Ignore policies and non-INPUT chains in the compatibility rule count.
			if strings.HasPrefix(line, "-A INPUT ") {
				total++
			}
		}
		return total
	}
	return counts["ip"] == count(ipv4) && counts["ip6"] == count(ipv6)
}

// knownCompatibilityInput requires both opaque matching and a recognized owned verdict.
func knownCompatibilityInput(expressions []map[string]json.RawMessage) bool {
	opaque, verdict := false, false
	// Inspect each expression group before claiming compatibility ownership.
	for _, expr := range expressions {
		// Preserve all expression kinds as evidence, rejecting unknown forms.
		for kind, data := range expr {
			currentOpaque, currentVerdict, valid := compatibilityExpression(kind, data)
			// Any unsupported expression invalidates the entire ownership claim.
			if !valid {
				return false
			}
			opaque = opaque || currentOpaque
			verdict = verdict || currentVerdict
		}
	}
	return opaque && verdict
}
